@app.post("/recognize")
@app.post("/recognize/")
async def recognize_faces(file: UploadFile = File(...)):
    print("\n📥 FaceModel /recognize request received", flush=True)
    print(f"   filename: {file.filename}", flush=True)
    
    try:
        contents = await file.read()
        print(f"   bytes_received: {len(contents)}", flush=True)
        npimg = np.frombuffer(contents, np.uint8)
        img = cv2.imdecode(npimg, cv2.IMREAD_COLOR)

        if img is None:
            print("   ❌ FaceModel could not decode image", flush=True)
            return {
                "success": False,
                "faces_detected": 0,
                "recognized_faces": [],
                "recognized_names": [],
                "unknown_faces": [],
                "results": [],
                "image_with_boxes": None,
                "timestamp": datetime.now().isoformat(),
                "error": "Invalid image file",
            }

        print("   📊 Loading known embeddings...", flush=True)
        known_embeddings, known_names = load_known_embeddings()
        print(f"   ✅ Loaded {len(known_names)} known embeddings", flush=True)

        # Detect faces in the uploaded image
        print("   🔍 Detecting faces...", flush=True)
        faces = get_encoder().detect_faces(img)
        print(f"   ✅ Detected {len(faces)} faces", flush=True)
        
        threshold_cos = 0.4  # tweak for sensitivity

        results = []
        recognized_faces = []
        unknown_faces = []

        for face in faces:
            emb = get_encoder().l2_normalize(face.embedding)
            name = "Unknown"
            confidence = 0.0

            if known_embeddings.size > 0:
                cos_sim = np.dot(known_embeddings, emb)
                idx = int(np.argmax(cos_sim))
                max_sim = float(cos_sim[idx])

                confidence = max_sim
                if max_sim > threshold_cos:
                    name = known_names[idx]

            print(f"   face_result: name={name}, confidence={confidence:.3f}", flush=True)

            x1, y1, x2, y2 = map(int, face.bbox)
            w = x2 - x1
            h = y2 - y1

            face_result = {
                "name": name,
                "confidence": confidence,
                "bbox": [x1, y1, w, h],
            }
            results.append(face_result)

            if name == "Unknown":
                unknown_faces.append(face_result)
            else:
                recognized_faces.append(face_result)

            cv2.rectangle(img, (x1, y1), (x2, y2), (0, 255, 0), 2)
            cv2.putText(img, f"{name} ({confidence:.2%})", (x1, y1 - 10),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 255, 0), 2)

        recognized_names = []
        for r in recognized_faces:
            nm = r["name"]
            if nm not in recognized_names:
                recognized_names.append(nm)

        print(f"   recognized_names: {recognized_names}", flush=True)
        print(f"   unknown_faces: {len(unknown_faces)}", flush=True)

        _, buffer = cv2.imencode('.jpg', img)
        image_base64 = base64.b64encode(buffer).decode('utf-8')

        return {
            "success": True,
            "faces_detected": len(results),
            "recognized_faces": recognized_faces,
            "recognized_names": recognized_names,
            "unknown_faces": unknown_faces,
            "results": results,
            "image_with_boxes": image_base64,
            "timestamp": datetime.now().isoformat(),
        }
    
    except Exception as e:
        print(f"   ❌ Error processing image: {str(e)}", flush=True)
        import traceback
        traceback.print_exc()
        return {
            "success": False,
            "faces_detected": 0,
            "recognized_faces": [],
            "recognized_names": [],
            "unknown_faces": [],
            "results": [],
            "image_with_boxes": None,
            "timestamp": datetime.now().isoformat(),
            "error": f"Face recognition error: {str(e)}",
        }


