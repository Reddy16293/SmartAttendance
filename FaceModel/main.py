def load_known_embeddings() -> tuple[np.ndarray, list[str]]:
    """Load known embeddings from PKL (preferred) or DB fallback."""
    # Preferred source: embeddings generated by generate_embeddings.py
    if os.path.exists(EMBEDDINGS_MASTER_PATH):
        with open(EMBEDDINGS_MASTER_PATH, "rb") as f:
            all_embeddings = pickle.load(f)

        known_names = list(all_embeddings.keys())
        known_embeddings = np.array([all_embeddings[name] for name in known_names])
        return known_embeddings, known_names

    # Fallback source: legacy DB records
    db: Session = SessionLocal()
    persons = db.query(Person).all()
    known_embeddings = []
    known_names = []

    for p in persons:
        emb = pickle.loads(p.embedding)
        known_embeddings.append(emb)
        known_names.append(p.name)
    db.close()

    return (np.array(known_embeddings) if known_embeddings else np.array([]), known_names)


def get_encoder() -> FaceEncoder:
    global encoder
    if encoder is None:
        try:
            print("🤖 Initializing FaceEncoder...", flush=True)
            encoder = FaceEncoder()
            print("✅ FaceEncoder initialized successfully", flush=True)
        except Exception as e:
            print(f"❌ Failed to initialize FaceEncoder: {e}", flush=True)
            raise
    return encoder

